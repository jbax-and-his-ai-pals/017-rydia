"""Build the patch: clean ROM -> generated data -> asar -> BPS.

Usage: python tools/build.py

Outputs (all in build/, ignored by git):
  rydia.sfc   patched ROM, for testing only; never distribute it
  rydia.bps   the patch to distribute (apply to a clean FF2 US v1.1 ROM)
  rydia.sym   asar symbols (WLA format) for Mesen
  gen/        assembly generated from data/*.csv

Tool paths default to C:\\tools; override with the ASAR and FLIPS env vars.
"""

import csv
import hashlib
import os
import shutil
import subprocess
import sys
import zlib
from pathlib import Path

from check_rom import check
from ff4rom import ROOT, find_rom

ASAR = os.environ.get("ASAR", r"C:\tools\asar-1.91\asar.exe")
FLIPS = os.environ.get("FLIPS", r"C:\tools\flips-v198\flips.exe")
BUILD = ROOT / "build"
GEN = BUILD / "gen"
SPECIES = 224


def gen_data() -> Path:
    """Write build/gen/data.asm from data/monsters.csv."""
    with (ROOT / "data" / "monsters.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if len(rows) != SPECIES:
        sys.exit(f"data/monsters.csv has {len(rows)} rows, expected {SPECIES}")

    bits = bytearray(SPECIES // 8)
    for r in rows:
        flag = r["capturable"].strip().lower()
        if flag not in ("y", "n"):
            sys.exit(f"data/monsters.csv: species {r['id']} capturable must be y or n, not {r['capturable']!r}")
        if flag == "y":
            s = int(r["id"], 16)
            bits[s >> 3] |= 1 << (s & 7)

    lines = [
        "; Generated by tools/build.py from data/monsters.csv. Do not edit.",
        "",
        "org $0EB439",
        "capturable_table:        ; species n: byte n>>3, bit n&7 (same layout as the plot flags)",
    ]
    for i in range(0, len(bits), 8):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in bits[i:i + 8]))
    lines += ["assert pc() <= $0EB6C0, \"data tables overflow their free block\"", ""]
    GEN.mkdir(parents=True, exist_ok=True)
    out = GEN / "data.asm"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen:   {out.relative_to(ROOT)} ({sum(r['capturable'].strip().lower() == 'y' for r in rows)} capturable)")
    return out


def run(cmd: list[str], what: str) -> None:
    result = subprocess.run(cmd, capture_output=True, text=True)
    lines = [line for line in (result.stdout + result.stderr).splitlines()
             if line.strip() and not line.startswith("Please wait")
             and "successfully" not in line]
    if lines:
        print("\n".join(f"       {line}" for line in lines))
    if result.returncode != 0:
        sys.exit(f"{what} failed (exit {result.returncode})")


def main() -> None:
    clean = find_rom()
    print(f"rom:   {clean.relative_to(ROOT)}")
    if not check(clean, quiet=True):
        sys.exit("The input ROM is not a clean FF2 US v1.1. Run: python tools/check_rom.py")

    BUILD.mkdir(exist_ok=True)
    rom = BUILD / "rydia.sfc"
    bps = BUILD / "rydia.bps"
    shutil.copyfile(clean, rom)
    gen_data()

    run([ASAR, "--fix-checksum=on", "--symbols=wla", f"--symbols-path={BUILD / 'rydia.sym'}",
         f"-I{BUILD}", str(ROOT / "asm" / "main.asm"), str(rom)], "asar")
    print(f"asar:  {rom.relative_to(ROOT)}")

    bps.unlink(missing_ok=True)
    run([FLIPS, "--create", "--bps-delta", str(clean), str(rom), str(bps)], "flips create")

    # Check the patch reproduces the build exactly.
    check_out = BUILD / "verify.sfc"
    run([FLIPS, "--apply", str(bps), str(clean), str(check_out)], "flips apply")
    same = check_out.read_bytes() == rom.read_bytes()
    check_out.unlink()
    if not same:
        sys.exit("BPS check failed: applying the patch does not reproduce build/rydia.sfc")

    data = rom.read_bytes()
    diff = sum(a != b for a, b in zip(data, clean.read_bytes()))
    print(f"bps:   {bps.relative_to(ROOT)} ({bps.stat().st_size:,} bytes), re-applies byte for byte")
    print(f"out:   {len(data):,} bytes, {diff} bytes differ from clean, "
          f"CRC32 {zlib.crc32(data) & 0xFFFFFFFF:08X}, SHA-1 {hashlib.sha1(data).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
