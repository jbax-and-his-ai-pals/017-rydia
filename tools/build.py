"""Build the patch: clean ROM -> generated data -> asar -> BPS.

Usage: python tools/build.py [--no-test-pacts]

By default (for now, while abilities are being playtested) New Game starts
owning every species with a live signature ability (data/monsters.csv,
call_verified=y); the first five fill Call and the rest are in the roster
picker (Y in the field Call list).
--no-test-pacts: the normal empty start. Build with it before running the
Mesen regression tests, which expect no pacts at New Game.

Outputs (all in build/, ignored by git):
  rydia.sfc   patched ROM, for testing only; never distribute it
  rydia.bps   the patch to distribute (apply to a clean FF2 US v1.1 ROM)
  rydia.sym   asar symbols (WLA format) for Mesen
  gen/        assembly generated from data/*.csv

Tool paths default to C:\\tools; override with the ASAR and FLIPS env vars.
"""

import csv
import hashlib
import os
import subprocess
import sys
import zlib
from pathlib import Path

from check_rom import check
from ff4rom import ROOT, Rom, find_rom
import late_game
import abilities

ASAR = os.environ.get("ASAR", r"C:\tools\asar-1.91\asar.exe")
FLIPS = os.environ.get("FLIPS", r"C:\tools\flips-v198\flips.exe")
BUILD = ROOT / "build"
GEN = BUILD / "gen"
SPECIES = 224
SOURCE_SIZE = 0x100000
OUTPUT_SIZE = 0x200000
LOROM_SIZE_HEADER = 0x7FD7
LOROM_MAP_MODE = 0x7FD5
LOROM_CARTRIDGE_TYPE = 0x7FD6
LOROM_SRAM_SIZE = 0x7FD8
LOROM_COMPLEMENT = 0x7FDC
LOROM_CHECKSUM = 0x7FDE
EXPECTED_LOROM_MAP_MODE = 0x20
OUTPUT_SIZE_CODE = 0x0B  # SNES header ROM size is log2(size in KiB): 2 MiB = 2048 KiB.


def gen_data() -> Path:
    """Write build/gen/data.asm from data/monsters.csv."""
    with (ROOT / "data" / "monsters.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if len(rows) != SPECIES:
        sys.exit(f"data/monsters.csv has {len(rows)} rows, expected {SPECIES}")

    bits = bytearray(SPECIES // 8)
    for r in rows:
        flag = r["capturable"].strip().lower()
        if flag not in ("y", "n"):
            sys.exit(f"data/monsters.csv: species {r['id']} capturable must be y or n, not {r['capturable']!r}")
        if flag == "y":
            s = int(r["id"], 16)
            bits[s >> 3] |= 1 << (s & 7)

    lines = [
        "; Generated by tools/build.py from data/monsters.csv. Do not edit.",
        "",
        "org !call_data",
        "capturable_table:        ; species n: byte n>>3, bit n&7 (same layout as the plot flags)",
    ]
    for i in range(0, len(bits), 8):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in bits[i:i + 8]))
    try:
        abil, live = abilities.table(Rom(), rows)
    except ValueError as e:
        sys.exit(f"data/monsters.csv: {e}")
    # Summon sprite maps (asm/ability.asm): for a grid of W x H 16x16 sprites,
    # the tile of each sprite, row by row, mirrored (summons face left).
    lines.append("summon_map_ptrs:         ; (W-1)*4 + (H-1), W 1-8, H 1-4")
    for w in range(1, 9):
        lines.append("    dw " + ", ".join(f"summon_map_{w}_{h}&$FFFF" for h in range(1, 5)))
    for w in range(1, 9):
        for h in range(1, 5):
            tiles = [y * 0x20 + (w - 1 - x) * 2 for y in range(h) for x in range(w)]
            lines.append(f"summon_map_{w}_{h}:")
            lines.append("    db " + ", ".join(f"${t:02X}" for t in tiles))
    try:
        cnames = abilities.names(Rom(), rows)
    except ValueError as e:
        sys.exit(f"data/monsters.csv: {e}")
    # Generic Call slots (asm/slots.asm): slot i is spell slot_ids[i]; slot_of
    # maps a spell ID back to its slot, $FF for none. Slots 0-4 keep $31-$35 so
    # old saves' first five stay where they were.
    slot_ids = list(range(0x31, 0x40)) + list(range(0x40, 0x48)) + [0x0C]
    assert len(slot_ids) == 24 and len(set(slot_ids)) == 24
    slot_of = [0xFF] * 256
    for i, sp in enumerate(slot_ids):
        slot_of[sp] = i
    lines.append("slot_ids:                ; 24 slot tokens, see asm/slots.asm")
    lines.append("    db " + ", ".join(f"${b:02X}" for b in slot_ids))
    lines.append("slot_of:                 ; spell ID -> slot, $FF none")
    for i in range(0, 256, 16):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in slot_of[i:i + 16]))
    lines.append("call_name_table:         ; 5 letters per species (call_name), Call menus")
    for i in range(0, len(cnames), 15):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in cnames[i:i + 15]))
    lines.append("call_ability_table:      ; 8 bytes per species, see asm/ability.asm")
    for i in range(0, len(abil), 16):
        lines.append("    db " + ", ".join(f"${b:02X}" for b in abil[i:i + 16]))
    lines += ["assert pc() <= !call_data_end, \"generated call data overflows its reserved block\"", ""]
    GEN.mkdir(parents=True, exist_ok=True)
    out = GEN / "data.asm"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen:   {out.relative_to(ROOT)} ({sum(r['capturable'].strip().lower() == 'y' for r in rows)} capturable, "
          f"{len(live)} live abilities)")
    return out


def test_pacts() -> list[int]:
    """Species with a live signature ability (data/monsters.csv, call_verified=y)."""
    with (ROOT / "data" / "monsters.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return [int(r["id"], 16) for r in rows if (r.get("call_verified") or "").strip().lower() == "y"]


def gen_newgame(clean: Path, pacts=()) -> None:
    """Write build/gen/newgame.asm: event $10 and the new-game WRAM table.
    pacts: species New Game starts with (only for --test-pacts builds)."""
    rom = Rom(clean)
    writes = late_game.writes(rom, pacts)
    lines = [
        "; Generated by tools/build.py from tools/late_game.py. Do not edit.",
        "",
        "org $1283E0              ; event $10 (the opening): load the overworld at the start spot",
        "    db " + ", ".join(f"${b:02X}" for b in late_game.start_event()),
        "",
        "org !newgame_table",
        "newgame_data:            ; entries: dw WRAM address, length; then the bytes. Ends with dw 0",
    ]
    total = 0
    for addr, data in writes:
        lines.append(f"    dw ${addr:04X}, {len(data)}")
        for i in range(0, len(data), 16):
            lines.append("    db " + ", ".join(f"${b:02X}" for b in data[i:i + 16]))
        total += 4 + len(data)
    lines += ["    dw $0000", "assert pc() <= !newgame_table_end, \"new-game data overflows its reserved block\"", ""]
    (GEN / "newgame.asm").write_text("\n".join(lines), encoding="utf-8")
    print(f"gen:   {(GEN / 'newgame.asm').relative_to(ROOT)} ({len(writes)} writes, {total + 2} bytes)")


def run(cmd: list[str], what: str) -> None:
    result = subprocess.run(cmd, capture_output=True, text=True)
    lines = [line for line in (result.stdout + result.stderr).splitlines()
             if line.strip() and not line.startswith("Please wait")
             and "successfully" not in line]
    if lines:
        print("\n".join(f"       {line}" for line in lines))
    if result.returncode != 0:
        sys.exit(f"{what} failed (exit {result.returncode})")


def validate_expanded_rom(data: bytes, clean: bytes) -> None:
    """Reject output that is not a checksummed 2 MiB LoROM matching base metadata."""
    if len(clean) != SOURCE_SIZE:
        raise ValueError(f"clean ROM is {len(clean):,} bytes, expected {SOURCE_SIZE:,}")
    if len(data) != OUTPUT_SIZE:
        raise ValueError(f"expanded ROM is {len(data):,} bytes, expected {OUTPUT_SIZE:,}")
    if clean[LOROM_MAP_MODE] != EXPECTED_LOROM_MAP_MODE:
        raise ValueError(f"clean ROM map mode is ${clean[LOROM_MAP_MODE]:02X}, expected LoROM $20")
    if data[LOROM_MAP_MODE] != clean[LOROM_MAP_MODE]:
        raise ValueError("expanded ROM map mode changed")
    if data[LOROM_CARTRIDGE_TYPE] != clean[LOROM_CARTRIDGE_TYPE]:
        raise ValueError("expanded ROM cartridge type changed")
    if data[LOROM_SRAM_SIZE] != clean[LOROM_SRAM_SIZE]:
        raise ValueError("expanded ROM SRAM size metadata changed")
    if data[LOROM_SIZE_HEADER] != OUTPUT_SIZE_CODE:
        raise ValueError(
            f"ROM size header is ${data[LOROM_SIZE_HEADER]:02X}, expected ${OUTPUT_SIZE_CODE:02X} (2 MiB)"
        )
    complement = int.from_bytes(data[LOROM_COMPLEMENT:LOROM_CHECKSUM], "little")
    checksum = int.from_bytes(data[LOROM_CHECKSUM:LOROM_CHECKSUM + 2], "little")
    if (checksum ^ complement) != 0xFFFF:
        raise ValueError("ROM checksum complement does not match checksum")
    computed = sum(data) & 0xFFFF
    if checksum != computed:
        raise ValueError(f"ROM checksum is ${checksum:04X}, computed ${computed:04X}")


def expanded_diff_count(expanded: bytes, clean: bytes) -> int:
    """Count changed and appended bytes, rather than truncating at zip's shorter input."""
    return sum(a != b for a, b in zip(expanded, clean)) + abs(len(expanded) - len(clean))


def main() -> None:
    clean = find_rom()
    print(f"rom:   {clean.relative_to(ROOT)}")
    if not check(clean, quiet=True):
        sys.exit("The input ROM is not a clean FF2 US v1.1. Run: python tools/check_rom.py")

    BUILD.mkdir(exist_ok=True)
    rom = BUILD / "rydia.sfc"
    bps = BUILD / "rydia.bps"
    clean_data = clean.read_bytes()
    if len(clean_data) != SOURCE_SIZE:
        sys.exit(f"The clean ROM must be exactly {SOURCE_SIZE:,} bytes before expansion")
    rom.write_bytes(clean_data + b"\xFF" * (OUTPUT_SIZE - SOURCE_SIZE))
    gen_data()
    pacts = [] if "--no-test-pacts" in sys.argv[1:] else test_pacts()
    if pacts:
        print(f"test:  New Game starts with {len(pacts)} pacts: " + " ".join(f"{s:02X}" for s in pacts))
    gen_newgame(clean, pacts)

    run([ASAR, "--fix-checksum=on", "--symbols=wla", f"--symbols-path={BUILD / 'rydia.sym'}",
         f"-I{BUILD}", str(ROOT / "asm" / "main.asm"), str(rom)], "asar")
    try:
        validate_expanded_rom(rom.read_bytes(), clean_data)
    except ValueError as exc:
        sys.exit(f"Expanded ROM validation failed: {exc}")
    print(f"asar:  {rom.relative_to(ROOT)}")

    bps.unlink(missing_ok=True)
    run([FLIPS, "--create", "--bps-delta", str(clean), str(rom), str(bps)], "flips create")

    # Check the patch reproduces the build exactly.
    check_out = BUILD / "verify.sfc"
    run([FLIPS, "--apply", str(bps), str(clean), str(check_out)], "flips apply")
    same = check_out.read_bytes() == rom.read_bytes()
    check_out.unlink()
    if not same:
        sys.exit("BPS check failed: applying the patch does not reproduce build/rydia.sfc")

    data = rom.read_bytes()
    validate_expanded_rom(data, clean_data)
    diff = expanded_diff_count(data, clean_data)
    print(f"bps:   {bps.relative_to(ROOT)} ({bps.stat().st_size:,} bytes), re-applies byte for byte")
    print(f"out:   {len(data):,} bytes, {diff} bytes differ from clean, "
          f"CRC32 {zlib.crc32(data) & 0xFFFFFFFF:08X}, SHA-1 {hashlib.sha1(data).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
