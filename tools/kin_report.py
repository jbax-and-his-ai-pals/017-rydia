"""Kin and chapter report: which kin each chapter's regions can supply.

Usage: python tools/kin_report.py      writes notes/kin-report.md

Joins data/monsters.csv (kin, capture_tier, capturable), data/encounters.csv
(where each species appears in random fights) and data/chapters.csv (which
chapter each location belongs to). A species belongs to the first chapter
whose areas contain it. Kin batches per chapter follow the chapter outline in
notes/storyboard.md.
"""

import csv
from collections import Counter, defaultdict

from ff4rom import ROOT
import kin as kin_mod

BATCHES = {"1": ["Wild", "Sky"], "2": ["Beast", "Shade"], "3": ["Construct"], "4": ["Dragon"],
           "5": ["Sea"], "8": ["Arcane"]}
ORDER = ["1", "2", "3", "4", "5", "6", "7", "8", "final"]
SHORT = 3   # a batch kin with fewer new species than this in its chapter is flagged
LIKES = ["sleep", "charm", "confuse", "paralyze", "slow", "stop", "blind", "poison", "mute",
         "low_hp", "critical_hp", "alone", "level_gap"]


def read(name):
    with (ROOT / "data" / name).open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def location(area_name: str) -> str:
    first = area_name.split(", ")[0]
    if first.startswith("near "):
        first = first[5:]
    return first.split(":")[0].strip()


def main() -> None:
    monsters = {r["id"]: r for r in read("monsters.csv") if r["capturable"] == "y"}
    rules = {(r["world"], r["location"]): r["chapter"] for r in read("chapters.csv")}
    where = defaultdict(set)          # chapter -> species ids
    unknown_areas = set()
    for e in read("encounters.csv"):
        sid = e["species"]
        if sid not in monsters:
            continue
        ch = rules.get((e["world"], location(e["area_name"])))
        if ch is None:
            ch = "unknown"
            unknown_areas.add(f"{e['world']}: {e['area_name']}")
        where[ch].add(sid)

    first = {}
    for ch in ORDER:
        for sid in where.get(ch, ()):
            first.setdefault(sid, ch)
    leftover = {"unplaced": where.get("unplaced", set()) - set(first),
                "unknown": where.get("unknown", set()) - set(first) - where.get("unplaced", set())}
    nowhere = sorted(set(monsters) - set(first) - leftover["unplaced"] - leftover["unknown"])

    kins = kin_mod.KIN
    out = ["# Kin and chapters", "",
           "Generated by `python tools/kin_report.py` from `data/monsters.csv`, `data/encounters.csv` "
           "and `data/chapters.csv`. Roadmap M1. Edit the CSVs, not this file.", ""]

    total = Counter(r["kin"] for r in monsters.values())
    src = Counter(r["kin_source"] for r in monsters.values())
    out += ["## Kin totals", "",
            f"{len(monsters)} capturable species: " + ", ".join(f"{k} {total[k]}" for k in kins) + ".",
            f"Sources: {src['rom']} from the ROM's creature type, {src['curated']} curated in `tools/kin.py`"
            + (f", {src['hand']} edited by hand" if src['hand'] else "") + ".", ""]

    out += ["## New species per chapter, by kin", "",
            "Species counted in the first chapter whose areas contain them. **Bold** marks the chapter's kin batch.", "",
            "| Chapter | " + " | ".join(kins) + " | New | Tier (min–max, mean) |",
            "| --- | " + " | ".join("---" for _ in kins) + " | --- | --- |"]
    shortfalls = []
    for ch in ORDER:
        new = [sid for sid, c in first.items() if c == ch]
        c = Counter(monsters[s]["kin"] for s in new)
        cells = []
        for k in kins:
            v = str(c[k])
            if k in BATCHES.get(ch, []):
                v = f"**{v}**"
                if c[k] < SHORT:
                    shortfalls.append(f"Chapter {ch}: {k} has {c[k]} new species (want {SHORT}+)")
            cells.append(v)
        tiers = [int(monsters[s]["capture_tier"]) for s in new]
        tier = f"{min(tiers)}–{max(tiers)}, {sum(tiers) / len(tiers):.1f}" if tiers else "—"
        out.append(f"| {ch} | " + " | ".join(cells) + f" | {len(new)} | {tier} |")
    out.append("")

    out += ["## Kin batch check", ""]
    out += [f"- {s}" for s in shortfalls] or ["- Every chapter's batch kin has at least "
                                               f"{SHORT} new species."]
    for ch, batch in BATCHES.items():
        for k in batch:
            avail = sum(1 for s in where.get(ch, ()) if monsters[s]["kin"] == k)
            out.append(f"- Chapter {ch} {k}: {avail} available in its areas (new or repeat).")
    out.append("")

    def names(ids):
        return ", ".join(f"{monsters[s]['name']} ({monsters[s]['kin']})" for s in sorted(ids)) or "none"

    out += ["## Species outside the chapter outline", "",
            f"- **Only in unplaced areas** (Toroia, Cave Magnes, Silvera, Grotto Adamant, Tower of Zot, chocobo areas, "
            f"Giant of Babil): {names(leftover['unplaced'])}",
            f"- **Only in unrecognised maps:** {names(leftover['unknown'])}",
            f"- **Never in a random fight:** {names(nowhere)}", ""]
    if unknown_areas:
        out += ["Unrecognised areas: " + "; ".join(sorted(unknown_areas)), ""]

    review = [r for r in monsters.values() if r["name"] in kin_mod.REVIEW]
    out += ["## Kin guesses to review", "",
            ", ".join(f"{r['name']} → {r['kin']}" for r in sorted(review, key=lambda r: r["name"])) + ".", ""]

    out += ["## Capture data", "",
            "- `capture_tier`: 1 (easy) to 5 (hard), seeded from level (≤9, ≤19, ≤34, ≤59, 60+); boss-bit species are 5.",
            "- `capture_likes`: conditions that raise this species' odds. `capture_needs`: hard requirements, "
            "for a few rare species only. Both are semicolon lists, empty until curated.",
            "- Vocabulary: " + ", ".join(f"`{x}`" for x in LIKES) + ". `alone` means the last monster standing; "
            "`level_gap` means Rydia's level is well above the monster's.", ""]

    (ROOT / "notes" / "kin-report.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote notes/kin-report.md; {len(shortfalls)} batch shortfall(s); "
          f"{len(leftover['unplaced'])} only-unplaced, {len(nowhere)} never in random fights")


if __name__ == "__main__":
    main()
